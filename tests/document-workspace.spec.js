import { test, expect } from '@playwright/test';
const pdf = { name: 'replaced.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nfixture') };
const fileRow = (page, name) => page.locator('.document-registry-row').filter({ has: page.getByRole('button', { name, exact: true }) });
test('full-width registry opens exact files and history without preview or summary panels', async ({ page }) => {
  await page.goto('/tests/ui/document-workspace.html');
  const row = fileRow(page, 'b.pdf');
  await row.getByRole('button', { name: 'b.pdf', exact: true }).click();
  await expect(page.locator('.document-registry-preview, .document-registry-summary')).toHaveCount(0);
  await row.getByRole('button', { name: 'View', exact: true }).click();
  expect(await page.evaluate(() => window.fixtureOpened)).toMatchObject({ id: 'b', stop_id: 'p2', current_version_id: 'v-b' });
  await row.locator('input[type=file]').setInputFiles(pdf);
  await expect(fileRow(page, 'a.pdf').getByRole('button', { name: 'a.pdf', exact: true })).toBeDisabled();
  await expect(fileRow(page, 'replaced.pdf')).toBeVisible();
  expect(await page.evaluate(() => window.fixtureActions[0])).toMatchObject({ type: 'bol', documentId: 'b', stopId: 'p2', expectedVersionId: 'v-b', action: 'upload' });
  await fileRow(page, 'replaced.pdf').locator('summary').click();
  await fileRow(page, 'replaced.pdf').getByRole('button', { name: 'Version history' }).click();
  await expect(page.getByRole('dialog', { name: 'Version history' }).getByText('previous.pdf', { exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(fileRow(page, 'replaced.pdf').locator('summary')).toBeFocused();
});
test('add another D2 file and remove only that document', async ({ page }) => {
  await page.goto('/tests/ui/document-workspace.html');
  const original = fileRow(page, 'pod2.pdf');
  await original.locator('summary').click();
  await original.getByRole('button', { name: 'Add another file at this stop' }).click();
  const addRow = page.locator('.document-registry-row.is-add').filter({ hasText: 'D2 · Second Delivery' });
  await addRow.locator('input[type=file]').setInputFiles({ ...pdf, name: 'extra-pod.pdf' });
  await expect(fileRow(page, 'extra-pod.pdf')).toBeVisible();
  expect(await page.evaluate(() => window.fixtureActions[0])).toMatchObject({ type: 'pod', documentId: null, stopId: 'd2', expectedVersionId: null });
  const added = fileRow(page, 'extra-pod.pdf');
  await added.locator('summary').click();
  await added.getByRole('button', { name: 'Remove file', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove file', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(fileRow(page, 'extra-pod.pdf')).toHaveCount(0);
  await expect(fileRow(page, 'pod1.pdf')).toBeVisible();
  await expect(fileRow(page, 'pod2.pdf')).toBeVisible();
  expect(await page.evaluate(() => window.fixtureActions[1])).toMatchObject({ documentId: 'new-file', stopId: 'd2', expectedVersionId: 'new-new-file', action: 'remove' });
});
test('read-only table retains every stop and receipt without edit controls', async ({ page }) => {
  await page.goto('/tests/ui/document-workspace.html?readOnly');
  await fileRow(page, 'receipt.pdf').getByRole('button', { name: 'receipt.pdf', exact: true }).click();
  expect(await page.evaluate(() => window.fixtureOpened)).toMatchObject({ id: 'receipt', current_version_id: 'v-receipt' });
  await expect(page.locator('input[type=file]')).toHaveCount(0);
  await expect(page.getByRole('button', { name: /^Replace / })).toHaveCount(0);
  await fileRow(page, 'pod2.pdf').getByRole('button', { name: 'pod2.pdf', exact: true }).click();
  expect(await page.evaluate(() => window.fixtureOpened)).toMatchObject({ id: 'pod2', stop_id: 'd2', current_version_id: 'v-pod2' });
});

test('missing receipt has an Add action and supports upload, open, replacement and removal', async ({ page }) => {
  await page.goto('/tests/ui/document-workspace.html?missingReceipt');
  const receipt = page.locator('.document-registry-row').filter({ hasText: 'Payment receipt' });
  await expect(receipt.getByRole('button', { name: 'Add file', exact: true })).toBeVisible();
  const chooser = page.waitForEvent('filechooser');
  await receipt.getByRole('button', { name: 'Add file', exact: true }).click();
  await (await chooser).setFiles({ ...pdf, name: 'payment-receipt.pdf' });
  await expect(fileRow(page, 'payment-receipt.pdf')).toBeVisible();
  expect(await page.evaluate(() => window.fixtureActions[0])).toMatchObject({ type: 'receipt', documentId: 'receipt', stopId: null, expectedVersionId: null });
  await fileRow(page, 'payment-receipt.pdf').getByRole('button', { name: 'View', exact: true }).click();
  expect(await page.evaluate(() => window.fixtureOpened)).toMatchObject({ id: 'receipt', current_version_id: 'new-receipt' });
  await fileRow(page, 'payment-receipt.pdf').locator('input[type=file]').setInputFiles({ ...pdf, name: 'corrected-receipt.pdf' });
  await expect(fileRow(page, 'corrected-receipt.pdf')).toBeVisible();
  expect(await page.evaluate(() => window.fixtureActions[1])).toMatchObject({ type: 'receipt', documentId: 'receipt', expectedVersionId: 'new-receipt' });
  await fileRow(page, 'corrected-receipt.pdf').locator('summary').click();
  await fileRow(page, 'corrected-receipt.pdf').getByRole('button', { name: 'Remove file', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove file', exact: true }).click();
  await expect(receipt.getByRole('button', { name: 'Add file', exact: true })).toBeVisible();
  expect(await page.evaluate(() => window.fixtureActions[2])).toMatchObject({ type: 'receipt', action: 'remove', documentId: 'receipt' });
  await expect(fileRow(page, 'pod1.pdf')).toBeVisible();
  await expect(fileRow(page, 'a.pdf')).toBeVisible();
});
